"""Verify fold1, export word-level records, and write a reproducible data audit."""

import hashlib
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from archaeo_ner.data import ENTITY_TYPES, LABEL_NAMES, read_iob, split_statistics


def main():
    manifest = json.loads((ROOT / "data/manifest.json").read_text())
    statistics = {}
    converted = {}
    for split, filename in (("train", "train.txt"), ("validation", "val.txt"), ("test", "test.txt")):
        path = ROOT / "data/raw/fold1" / filename
        content = path.read_bytes()
        expected = manifest["files"][filename]
        if len(content) != expected["bytes"] or hashlib.sha256(content).hexdigest() != expected["sha256"]:
            raise ValueError(f"Checksum/size mismatch: {path}")
        converted[split] = read_iob(path)
        statistics[split] = split_statistics(converted[split])
        statistics[split]["sha256_verified"] = True

    destination = ROOT / "data/processed/fold1"
    destination.mkdir(parents=True, exist_ok=True)
    for split, records in converted.items():
        (destination / f"{split}.jsonl").write_text(
            "".join(json.dumps(record, ensure_ascii=False) + "\n" for record in records),
            encoding="utf-8",
        )
    (destination / "label_names.json").write_text(json.dumps(LABEL_NAMES, indent=2) + "\n")
    reports = ROOT / "reports"
    reports.mkdir(exist_ok=True)
    (reports / "data_statistics.json").write_text(json.dumps(statistics, indent=2) + "\n")
    lines = [
        "# Fold1 data audit", "",
        "Generated by `python scripts/prepare_data.py`. All three input files match",
        "the byte sizes and SHA-256 checksums in `data/manifest.json`.", "",
        "Original sentence boundaries, words, and labels are preserved. POS tags are",
        "ignored. JSONL records contain `id`, `tokens`, and integer `ner_tags`.",
        "The label-ID mapping is saved in `data/processed/fold1/label_names.json`.", "",
        "## Split sizes", "",
        "| Split | Sequences | Words | Min words | Max words | Mean words | Invalid IOB2 I-tags |",
        "| --- | ---: | ---: | ---: | ---: | ---: | ---: |",
    ]
    for split, stats in statistics.items():
        values = [stats[key] for key in ("sequences", "word_tokens", "min_words", "max_words", "mean_words", "invalid_iob2_inside_tags")]
        lines.append(f"| {split} | " + " | ".join(str(value) for value in values) + " |")
    lines += ["", "## Entity distribution", "",
              "Counts below are B-tag starts. They equal complete entity counts when",
              "the invalid IOB2 I-tag count above is zero. Percentages exclude O tokens.", "",
              "| Type | Train entities | Train share | Validation entities | Test entities |",
              "| --- | ---: | ---: | ---: | ---: |"]
    total = sum(statistics["train"]["entity_starts"].values())
    for entity in ENTITY_TYPES:
        counts = [statistics[split]["entity_starts"][entity] for split in statistics]
        share = f"{counts[0] / total:.1%}" if total else "n/a"
        lines.append(f"| {entity} | {counts[0]} | {share} | {counts[1]} | {counts[2]} |")
    lines += ["", "## Word-label distribution", "",
              "| Label | Train | Validation | Test |", "| --- | ---: | ---: | ---: |"]
    for label in LABEL_NAMES:
        counts = [str(stats["label_counts"][label]) for stats in statistics.values()]
        lines.append(f"| {label} | " + " | ".join(counts) + " |")
    lines += ["", "## Tokenization", "",
              "Run `python scripts/tokenize_data.py` to create Hugging Face Dataset",
              "features and align these word-level labels to subword tokens. See",
              "`reports/tokenization_audit.md` for the completed alignment audit.",
              "These are descriptive data counts, not model evaluation results.", ""]
    (reports / "data_audit.md").write_text("\n".join(lines), encoding="utf-8")
    print("Verified all fold1 checksums; exported word-level JSONL and reports/data_audit.md.")


if __name__ == "__main__":
    main()
